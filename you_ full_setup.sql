-- Khmer Inventory System: complete schema for the existing BIGINT products table.
-- BACK UP YOUR DATABASE FIRST. This script preserves existing products and profiles.
-- Assumptions: public.products(id BIGINT, name TEXT, sku TEXT, quantity INTEGER, price NUMERIC)
begin;

alter table public.products add column if not exists cost_price numeric(12,2) not null default 0;
alter table public.products add column if not exists image_url text;
alter table public.products add column if not exists category_id bigint;
alter table public.products add column if not exists brand_id bigint;

create table if not exists public.categories(
 id bigint generated by default as identity primary key,
 name text not null unique, description text, created_at timestamptz not null default now()
);
create table if not exists public.brands(
 id bigint generated by default as identity primary key,
 name text not null unique, description text, created_at timestamptz not null default now()
);
create table if not exists public.customers(
 id bigint generated by default as identity primary key,
 name text not null, phone text, email text, address text, created_at timestamptz not null default now()
);
create table if not exists public.suppliers(
 id bigint generated by default as identity primary key,
 name text not null, phone text, email text, address text, created_at timestamptz not null default now()
);
create table if not exists public.shop_settings(
 id integer primary key default 1 check(id=1), shop_name text default 'My Shop',
 shop_phone text, shop_address text, invoice_footer text default 'Thank you!',
 exchange_rate numeric(14,2) not null default 4100, updated_at timestamptz default now()
);
insert into public.shop_settings(id) values(1) on conflict(id) do nothing;

create table if not exists public.sales(
 id bigint generated by default as identity primary key, invoice_no text unique not null,
 customer_name text, customer_phone text, subtotal_usd numeric(12,2) not null,
 discount_usd numeric(12,2) not null default 0, total_usd numeric(12,2) not null,
 payment_currency text not null check(payment_currency in('USD','KHR')),
 paid_amount numeric(14,2) not null, paid_usd numeric(12,2) not null,
 change_amount numeric(14,2) not null default 0, exchange_rate numeric(14,2) not null,
 cost_total_usd numeric(12,2) not null default 0, created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);
create table if not exists public.sale_items(
 id bigint generated by default as identity primary key,
 sale_id bigint not null references public.sales(id) on delete cascade,
 product_id bigint not null references public.products(id),
 product_name text not null, sku text, quantity integer not null check(quantity>0),
 unit_price_usd numeric(12,2) not null, unit_cost_usd numeric(12,2) not null default 0,
 line_total_usd numeric(12,2) not null
);
create table if not exists public.stock_movements(
 id bigint generated by default as identity primary key,
 product_id bigint references public.products(id), product_name text not null,
 movement_type text not null check(movement_type in('in','out')),
 quantity integer not null check(quantity>0), note text,
 created_by uuid references auth.users(id), created_at timestamptz not null default now()
);
create table if not exists public.expenses(
 id bigint generated by default as identity primary key, title text not null,
 category text, amount_usd numeric(12,2) not null check(amount_usd>0),
 expense_date date not null default current_date, created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);

-- Ensure existing profile roles are constrained to owner/staff.
alter table public.profiles add column if not exists display_name text;
alter table public.profiles add column if not exists role text not null default 'staff';
alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles add constraint profiles_role_check check(role in('owner','staff'));

-- Role helpers used by RLS and security-definer RPCs.
create or replace function public.current_user_role() returns text
language sql stable security definer set search_path=public
as $$ select role from public.profiles where id=auth.uid() $$;
create or replace function public.is_owner() returns boolean
language sql stable security definer set search_path=public
as $$ select coalesce(public.current_user_role()='owner',false) $$;

-- Policies: authenticated users may operate the POS data; only owners manage users/settings.
do $$ declare t text; begin
 foreach t in array array['products','categories','brands','customers','suppliers','sales','sale_items','stock_movements','expenses'] loop
  execute format('alter table public.%I enable row level security',t);
  execute format('drop policy if exists %I on public.%I',t||'_auth_select',t);
  execute format('create policy %I on public.%I for select to authenticated using (true)',t||'_auth_select',t);
  execute format('drop policy if exists %I on public.%I',t||'_auth_insert',t);
  execute format('create policy %I on public.%I for insert to authenticated with check (public.current_user_role() in (''owner'',''staff''))',t||'_auth_insert',t);
  execute format('drop policy if exists %I on public.%I',t||'_auth_update',t);
  execute format('create policy %I on public.%I for update to authenticated using (public.current_user_role() in (''owner'',''staff'')) with check (public.current_user_role() in (''owner'',''staff''))',t||'_auth_update',t);
  execute format('drop policy if exists %I on public.%I',t||'_auth_delete',t);
  execute format('create policy %I on public.%I for delete to authenticated using (public.is_owner())',t||'_auth_delete',t);
 end loop;
end $$;
alter table public.profiles enable row level security;
drop policy if exists profiles_select_auth on public.profiles;
create policy profiles_select_auth on public.profiles for select to authenticated using (id=auth.uid() or public.is_owner());
drop policy if exists profiles_update_owner on public.profiles;
create policy profiles_update_owner on public.profiles for update to authenticated using (public.is_owner()) with check (public.is_owner());
alter table public.shop_settings enable row level security;
drop policy if exists settings_read_auth on public.shop_settings;
create policy settings_read_auth on public.shop_settings for select to authenticated using(true);
drop policy if exists settings_owner_write on public.shop_settings;
create policy settings_owner_write on public.shop_settings for all to authenticated using(public.is_owner()) with check(public.is_owner());

-- Atomic POS checkout: locks stock rows, validates payment and updates stock in one transaction.
create or replace function public.create_sale(
 p_customer_name text,p_customer_phone text,p_items jsonb,p_discount_usd numeric,
 p_payment_currency text,p_paid_amount numeric,p_exchange_rate numeric
) returns jsonb language plpgsql security definer set search_path=public as $$
declare v_id bigint; v_invoice text; v_sub numeric(12,2):=0; v_cost numeric(12,2):=0;
 v_disc numeric(12,2); v_total numeric(12,2); v_paid_usd numeric(12,2);
 v_change numeric(14,2); it jsonb; pr public.products%rowtype; q integer;
begin
 if auth.uid() is null or public.current_user_role() not in('owner','staff') then raise exception 'Not authorized'; end if;
 if p_payment_currency not in('USD','KHR') or p_exchange_rate<=0 or p_paid_amount<0 then raise exception 'Invalid payment'; end if;
 if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'Cart is empty'; end if;
 for it in select value from jsonb_array_elements(p_items) loop
  q:=(it->>'quantity')::integer;
  if q<=0 then raise exception 'Invalid quantity'; end if;
  select * into pr from public.products where id=(it->>'product_id')::bigint for update;
  if not found then raise exception 'Product not found'; end if;
  if coalesce(pr.quantity,0)<q then raise exception 'Not enough stock for %',pr.name; end if;
  v_sub:=v_sub+coalesce(pr.price,0)*q; v_cost:=v_cost+coalesce(pr.cost_price,0)*q;
 end loop;
 v_disc:=greatest(0,least(coalesce(p_discount_usd,0),v_sub)); v_total:=v_sub-v_disc;
 v_paid_usd:=case when p_payment_currency='USD' then p_paid_amount else p_paid_amount/p_exchange_rate end;
 if v_paid_usd<v_total then raise exception 'Payment is less than total'; end if;
 v_change:=case when p_payment_currency='USD' then p_paid_amount-v_total else p_paid_amount-v_total*p_exchange_rate end;
 v_invoice:='KIS-'||to_char(now(),'YYYYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,8));
 insert into public.sales(invoice_no,customer_name,customer_phone,subtotal_usd,discount_usd,total_usd,payment_currency,paid_amount,paid_usd,change_amount,exchange_rate,cost_total_usd,created_by)
 values(v_invoice,p_customer_name,p_customer_phone,v_sub,v_disc,v_total,p_payment_currency,p_paid_amount,v_paid_usd,greatest(0,v_change),p_exchange_rate,v_cost,auth.uid()) returning id into v_id;
 for it in select value from jsonb_array_elements(p_items) loop
  q:=(it->>'quantity')::integer;
  select * into pr from public.products where id=(it->>'product_id')::bigint for update;
  insert into public.sale_items(sale_id,product_id,product_name,sku,quantity,unit_price_usd,unit_cost_usd,line_total_usd)
  values(v_id,pr.id,pr.name,pr.sku,q,coalesce(pr.price,0),coalesce(pr.cost_price,0),coalesce(pr.price,0)*q);
  update public.products set quantity=quantity-q where id=pr.id;
  insert into public.stock_movements(product_id,product_name,movement_type,quantity,note,created_by)
  values(pr.id,pr.name,'out',q,'POS sale '||v_invoice,auth.uid());
 end loop;
 return jsonb_build_object('id',v_id,'invoice_no',v_invoice,'total_usd',v_total);
end $$;
revoke all on function public.create_sale(text,text,jsonb,numeric,text,numeric,numeric) from public;
grant execute on function public.create_sale(text,text,jsonb,numeric,text,numeric,numeric) to authenticated;

create or replace function public.record_stock_movement(p_product_id bigint,p_quantity integer,p_movement_type text,p_note text default '')
returns void language plpgsql security definer set search_path=public as $$
declare pr public.products%rowtype;
begin
 if auth.uid() is null or public.current_user_role() not in('owner','staff') then raise exception 'Not authorized'; end if;
 if p_quantity<=0 or p_movement_type not in('in','out') then raise exception 'Invalid stock movement'; end if;
 select * into pr from public.products where id=p_product_id for update;
 if not found then raise exception 'Product not found'; end if;
 if p_movement_type='out' and pr.quantity<p_quantity then raise exception 'Not enough stock'; end if;
 update public.products set quantity=case when p_movement_type='in' then quantity+p_quantity else quantity-p_quantity end where id=p_product_id;
 insert into public.stock_movements(product_id,product_name,movement_type,quantity,note,created_by)
 values(pr.id,pr.name,p_movement_type,p_quantity,p_note,auth.uid());
end $$;
revoke all on function public.record_stock_movement(bigint,integer,text,text) from public;
grant execute on function public.record_stock_movement(bigint,integer,text,text) to authenticated;

commit;
