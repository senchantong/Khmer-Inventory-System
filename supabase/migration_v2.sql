-- 9. Function to create sale and reduce stock safely
CREATE OR REPLACE FUNCTION public.create_sale(
    p_invoice_no TEXT,
    p_customer_name TEXT,
    p_customer_phone TEXT,
    p_discount NUMERIC,
    p_paid_amount NUMERIC,
    p_payment_currency TEXT,
    p_exchange_rate NUMERIC,
    p_items JSONB
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
    v_sale_id BIGINT;
    v_subtotal NUMERIC(12,2) := 0;
    v_total NUMERIC(12,2);
    v_item JSONB;
    v_product RECORD;
    v_qty NUMERIC(12,2);
    v_line_total NUMERIC(12,2);
    v_cost NUMERIC(12,2);
    v_discount NUMERIC(12,2);
    v_rate NUMERIC(12,2);
    v_paid NUMERIC(12,2);
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Login required';
    END IF;

    IF p_payment_currency NOT IN ('USD', 'KHR') THEN
        RAISE EXCEPTION 'Invalid payment currency';
    END IF;

    IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array'
       OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Sale must contain at least one item';
    END IF;

    v_discount := GREATEST(COALESCE(p_discount, 0), 0);
    v_rate := COALESCE(p_exchange_rate, 4100);
    v_paid := GREATEST(COALESCE(p_paid_amount, 0), 0);

    IF v_rate <= 0 THEN
        RAISE EXCEPTION 'Exchange rate must be greater than zero';
    END IF;

    -- Validate and calculate item totals using database prices.
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
    LOOP
        v_qty := (v_item->>'quantity')::NUMERIC;

        IF v_qty <= 0 THEN
            RAISE EXCEPTION 'Invalid item quantity';
        END IF;

        SELECT id, name, sku, quantity, price, cost_price
        INTO v_product
        FROM public.products
        WHERE id = (v_item->>'product_id')::BIGINT
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Product not found';
        END IF;

        IF v_product.quantity < v_qty THEN
            RAISE EXCEPTION 'Not enough stock for product: %',
                v_product.name;
        END IF;

        v_line_total := v_product.price * v_qty;
        v_subtotal := v_subtotal + v_line_total;
    END LOOP;

    IF v_discount > v_subtotal THEN
        RAISE EXCEPTION 'Discount cannot exceed subtotal';
    END IF;

    v_total := v_subtotal - v_discount;

    IF p_payment_currency = 'USD' THEN
        IF v_paid < v_total THEN
            RAISE EXCEPTION 'Insufficient payment';
        END IF;
    ELSE
        IF v_paid < (v_total * v_rate) THEN
            RAISE EXCEPTION 'Insufficient payment';
        END IF;
    END IF;

    INSERT INTO public.sales (
        invoice_no,
        customer_name,
        customer_phone,
        subtotal,
        discount,
        total,
        paid_amount,
        payment_currency,
        exchange_rate,
        change_amount
    )
    VALUES (
        p_invoice_no,
        p_customer_name,
        p_customer_phone,
        v_subtotal,
        v_discount,
        v_total,
        v_paid,
        p_payment_currency,
        v_rate,
        CASE
            WHEN p_payment_currency = 'USD'
                THEN v_paid - v_total
            ELSE v_paid - (v_total * v_rate)
        END
    )
    RETURNING id INTO v_sale_id;

    -- Insert sale items and reduce stock.
    FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
    LOOP
        v_qty := (v_item->>'quantity')::NUMERIC;

        SELECT id, name, sku, quantity, price, cost_price
        INTO v_product
        FROM public.products
        WHERE id = (v_item->>'product_id')::BIGINT
        FOR UPDATE;

        v_line_total := v_product.price * v_qty;
        v_cost := COALESCE(v_product.cost_price, 0);

        INSERT INTO public.sale_items (
            sale_id,
            product_id,
            product_name,
            sku,
            quantity,
            unit_price,
            cost_price,
            line_total
        )
        VALUES (
            v_sale_id,
            v_product.id,
            v_product.name,
            v_product.sku,
            v_qty,
            v_product.price,
            v_cost,
            v_line_total
        );

        UPDATE public.products
        SET quantity = quantity - v_qty
        WHERE id = v_product.id;
    END LOOP;

    RETURN v_sale_id;
END;
$$;

-- 10. Allow logged-in users to call the sale function
GRANT EXECUTE ON FUNCTION public.create_sale(
    TEXT, TEXT, TEXT, NUMERIC, NUMERIC, TEXT, NUMERIC, JSONB
) TO authenticated;

